"""Built-in Agent rules and the small set of workspace settings users can change."""

DEFAULT_PROCESSING = (
    "用中文整理当前已由订阅分类和标签选中的输入。只使用原文或订阅摘要中有依据的信息，"
    "区分事实、当事方声明和分析判断，保留真实来源与时间，不编造价格、结论或缺失细节。"
    "除证据不足、内容为空或明显不是有效更新外，不自行扩大或缩小订阅范围。"
)
DEFAULT_TEMPLATE = "标题：\n内容摘要：\n来源与原文链接（如有）：\n影响与后续关注（有依据时填写）："
FIELDS = {"output_template": 40000}
LEGACY_FIELDS = {
    "focus_prompt",
    "excluded_topics",
    "processing_prompt",
    "language",
    "additional_instructions",
}


def conversation_profile_for(workspace):
    profile = workspace.get("conversation_profile")
    return {
        "web_search_enabled": bool(profile.get("web_search_enabled"))
        if isinstance(profile, dict)
        else False
    }


def validate_conversation_profile(value):
    if not isinstance(value, dict) or set(value) - {"prompt", "web_search_enabled"}:
        raise ValueError("对话配置字段无效")
    enabled = value.get("web_search_enabled", False)
    if type(enabled) is not bool:
        raise ValueError("对话配置格式无效")
    # prompt was accepted by earlier versions, but is intentionally ignored.
    return {"web_search_enabled": enabled}


def profile_for(workspace, paths):
    if isinstance(workspace.get("ai_profile"), dict):
        template = workspace["ai_profile"].get("output_template") or DEFAULT_TEMPLATE
        return {"output_template": template[: FIELDS["output_template"]]}

    def legacy(name, fallback=""):
        p = paths.file(workspace["path"], name)
        return p.read_text(encoding="utf-8")[:40000] if p.is_file() else fallback

    template = legacy("docs/template.md", DEFAULT_TEMPLATE)
    old_template = "# 订阅更新\n\n标题：<title>\n内容摘要：<evidence-based content>\n来源：<source and original link if provided>\n影响与备注：<only when supported>"
    if template.strip() == old_template:
        template = DEFAULT_TEMPLATE
    return {
        "output_template": template or DEFAULT_TEMPLATE,
    }


def validate_profile(value):
    if not isinstance(value, dict) or any(
        k not in FIELDS and k not in LEGACY_FIELDS for k in value
    ):
        raise ValueError("工作区 AI 配置字段无效")
    template = value.get("output_template", DEFAULT_TEMPLATE)
    if not isinstance(template, str) or len(template) > FIELDS["output_template"]:
        raise ValueError("工作区 AI 配置过长或格式不正确：output_template")
    return {"output_template": template or DEFAULT_TEMPLATE}


def rules_for(workspace, paths):
    p = profile_for(workspace, paths)
    return {
        "AGENTS.md": "Read docs/event-task.md, docs/rules.md and docs/template.md, then process only the supplied event. These task-scoped rules are generated by the platform.",
        "docs/event-task.md": "Read the supplied event and its raw input. The source has already been selected by the subscription's category and tags. Apply the built-in整理规则 and template. Save the three provided outputs. Return the report or SKIP: reason when evidence is insufficient.",
        "docs/rules.md": DEFAULT_PROCESSING,
        "docs/template.md": p["output_template"] or DEFAULT_TEMPLATE,
    }
